-- Konri's Team per-mod forums
-- Run this script once in Supabase Dashboard -> SQL Editor.
-- Public can read; only users signed in with GitHub can create topics/replies.

create table if not exists public.forum_topics (
  id bigint generated by default as identity primary key,
  mod_slug text not null,
  title text not null check (char_length(title) between 1 and 100),
  body text not null check (char_length(body) between 1 and 5000),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.forum_posts (
  id bigint generated by default as identity primary key,
  topic_id bigint not null references public.forum_topics(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 3000),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists forum_topics_mod_created_idx
  on public.forum_topics (mod_slug, created_at desc);
create index if not exists forum_posts_topic_created_idx
  on public.forum_posts (topic_id, created_at asc);

alter table public.forum_topics enable row level security;
alter table public.forum_posts enable row level security;

drop policy if exists "Forum topics are public to read" on public.forum_topics;
create policy "Forum topics are public to read"
  on public.forum_topics for select
  using (true);

drop policy if exists "GitHub users can create forum topics" on public.forum_topics;
create policy "GitHub users can create forum topics"
  on public.forum_topics for insert to authenticated
  with check (
    auth.uid() = user_id
    and auth.jwt() -> 'app_metadata' ->> 'provider' = 'github'
  );

drop policy if exists "Authors can delete their own forum topics" on public.forum_topics;
create policy "Authors can delete their own forum topics"
  on public.forum_topics for delete to authenticated
  using (
    auth.uid() = user_id
    and auth.jwt() -> 'app_metadata' ->> 'provider' = 'github'
  );

drop policy if exists "Forum replies are public to read" on public.forum_posts;
create policy "Forum replies are public to read"
  on public.forum_posts for select
  using (true);

drop policy if exists "GitHub users can create forum replies" on public.forum_posts;
create policy "GitHub users can create forum replies"
  on public.forum_posts for insert to authenticated
  with check (
    auth.uid() = user_id
    and auth.jwt() -> 'app_metadata' ->> 'provider' = 'github'
    and exists (
      select 1 from public.forum_topics t where t.id = topic_id
    )
  );

drop policy if exists "Authors can delete their own forum replies" on public.forum_posts;
create policy "Authors can delete their own forum replies"
  on public.forum_posts for delete to authenticated
  using (
    auth.uid() = user_id
    and auth.jwt() -> 'app_metadata' ->> 'provider' = 'github'
  );
